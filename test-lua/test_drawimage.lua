-- Draw a larger 16x16 sprite
local largeSprite = {}
for i = 1, 256 do
    if i % 3 == 0 then
        largeSprite[i] = 0x3F
    elseif i % 3 == 1 then
        largeSprite[i] = 0x2E
    else
        largeSprite[i] = 0x16
    end
end

-- Draw a simple 4x4 sprite
local smallSprite = {
    0x20, 0x2E, 0x20, 0x2E,
    0x2E, 0x20, 0x2E, 0x20,
    0x20, 0x2E, 0x20, 0x2E,
    0x2E, 0x20, 0x2E, 0x20
}

function gui()
    -- Draw the sprite at position (10, 10)
    drawimage(10, 10, spriteData, 8, 8)
    
    -- Draw another sprite at a different position with different colors
    drawimage(100, 50, spriteData2, 8, 8)
    
    -- Draw a larger 16x16 sprite
    drawimage(150, 100, largeSprite, 16, 16)
    
    -- Draw a simple 4x4 sprite
    drawimage(200, 200, smallSprite, 4, 4)
    
    -- Show FPS for reference
    local fps = getfps()
    drawtext(4, 4, string.format("drawimage test - FPS: %.1f", fps), 0x2E)
end

